  const [hiddenChatIds, setHiddenChatIds] = useState<string[]>(() => loadLocal<string[]>(HIDDEN_CHAT_KEY, []));
  const [notes, setNotes] = useState<MessageNote[]>(() => loadLocal<MessageNote[]>(NOTES_KEY, []));
  const [systemDraft, setSystemDraft] = useState('');
  const [selectionMode, setSelectionMode] = useState(false);
  const [selectedMessageIds, setSelectedMessageIds] = useState<Set<string>>(new Set());
  const [forwardItems, setForwardItems] = useState<MessageReference[]>([]);
  const [forwardFriendIds, setForwardFriendIds] = useState<string[]>([]);
  const [forwarding, setForwarding] = useState(false);
  const [noteEditorOpen, setNoteEditorOpen] = useState(false);
  const [editingNoteId, setEditingNoteId] = useState('');
  const [noteTitle, setNoteTitle] = useState('');
