  const persistMessageCenterState = (overrides: Partial<{
    dismissedIds: string[];
    replies: LocalReply[];
    readIds: string[];
    hiddenChatIds: string[];
    notes: MessageNote[];
  }> = {}) => {
    const state = { dismissedIds, replies, readIds, hiddenChatIds, notes, ...overrides };
    saveLocal(DISMISSED_KEY, state.dismissedIds);
    saveLocal(REPLIES_KEY, state.replies);
    saveLocal(READ_KEY, state.readIds);
    saveLocal(HIDDEN_CHAT_KEY, state.hiddenChatIds);
    saveLocal(NOTES_KEY, state.notes);
    void window.electronAPI.saveMessageCenterState?.(state);
  };

  useEffect(() => {
    let cancelled = false;
    const request = window.electronAPI.loadMessageCenterState?.();
    if (!request) {
      setMessageStateLoaded(true);
      persistMessageCenterState();
      return () => { cancelled = true; };
    }
    void request.then(result => {
      if (cancelled || !result?.success) return;
      if (result.state) {
        const nextDismissedIds = Array.isArray(result.state.dismissedIds) ? result.state.dismissedIds : [];
        const nextReplies = Array.isArray(result.state.replies) ? result.state.replies as LocalReply[] : [];
        const nextReadIds = Array.isArray(result.state.readIds) ? result.state.readIds : [];
        const nextHiddenChatIds = Array.isArray(result.state.hiddenChatIds) ? result.state.hiddenChatIds : [];
        const nextNotes = Array.isArray(result.state.notes) ? result.state.notes as MessageNote[] : [];
        setDismissedIds(nextDismissedIds);
        setReplies(nextReplies);
        setReadIds(nextReadIds);
        setHiddenChatIds(nextHiddenChatIds);
        setNotes(nextNotes);
      } else {
        persistMessageCenterState();
      }
    }).catch(() => {}).finally(() => {
      if (!cancelled) setMessageStateLoaded(true);
    });
    return () => { cancelled = true; };
  // Read once per workspace-mounted message center. The main process owns the
  // workspace path, while localStorage is only a migration fallback.
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const systemMessages = useMemo(
    () => [...buildNoteMessages(notes), ...buildSystemMessages(projects, projectDocs, reviews)]
      .filter(item => !dismissedIds.includes(item.id))
      .sort((a, b) => safeDateMs(b.createdAt) - safeDateMs(a.createdAt)),
    [dismissedIds, notes, projectDocs, projects, reviews],
  );
  const unreadSystemMessages = useMemo(() => systemMessages.filter(item => !readIds.includes(item.id)), [readIds, systemMessages]);
  const visibleFriends = useMemo(() => {
    const query = keyword.trim().toLocaleLowerCase();
    if (!query) return friends;
    return friends.filter(friend => [friend.name, friend.nickname, friend.email, friend.host]
      .filter(Boolean).some(value => String(value).toLocaleLowerCase().includes(query)));
  }, [friends, keyword]);
  const sortedJobs = useMemo(() => {
    const businessJobs = aiJobs.filter(job => !job.id.startsWith('external:'));
    // Model lifecycle events normally carry the same requestId as a business
    // job. Older/unscoped events do not; hide those generic cards when a real
    // task finished at the same time so one AI task remains one chat bubble.
    return aiJobs
      .filter(job => {
        if (!job.id.startsWith('external:')) return true;
        const time = safeDateMs(job.finishedAt || job.updatedAt || job.createdAt);
        return !businessJobs.some(task => Math.abs(safeDateMs(task.finishedAt || task.updatedAt || task.createdAt) - time) < 12_000);
      })
      .sort((a, b) => safeDateMs(b.updatedAt) - safeDateMs(a.updatedAt));
  }, [aiJobs]);
